func readAllFile(path string) ([]byte, error) {
	return os.ReadFile(path)
}

func writeAll(t *testing.T, path string, data []byte) {
	t.Helper()
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

